package com.dksystems.tracephone.domain.model

/**
 * 앱별 목록을 어떤 모양으로 그릴지.
 *
 * 같은 값을 두 가지로 보여준다. 한 화면에 몇 개가 들어오느냐와
 * 막대를 얼마나 또렷이 보느냐가 서로 맞바꿈 관계라, 어느 쪽이 나은지는 쓰는 사람이 정한다.
 */
enum class AppListLayout {

    /**
     * 두 줄. 이름 아래에 모바일 막대를 진하게 그린다.
     *
     * 막대가 또렷해 앱끼리 비교하기 쉽다. 대신 한 화면에 들어오는 앱이 절반이다.
     */
    DETAILED,

    /**
     * 한 줄. 줄 뒤에 깔리는 옅은 띠의 길이가 모바일 사용량이다.
     *
     * 한 화면에 두 배로 들어온다. 대신 띠가 옅어 비슷한 두 앱은 구분되지 않는다.
     */
    COMPACT
}
